import { describe, expect, it } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import { blank, type Img } from './image';
import { findGlow, GlowLock, glowPreview, splitGlow } from './glow';
import { tempDir } from '../../server/test/fixtures/temp-dir';

function img480(): Img {
  const img = blank(480, 270);
  for (let i = 0; i < 480 * 270; i++) img.data.set([20, 12, 30, 255], i * 4); // dark violet
  return img;
}
const put = (img: Img, x: number, y: number, rgb: number[]) => img.data.set([...rgb, 255], (y * img.w + x) * 4);

describe('findGlow', () => {
  it('bright saturated pixels are candidates; dark or grey ones are not', () => {
    const img = img480();
    put(img, 10, 10, [255, 60, 140]); // neon pink
    put(img, 11, 10, [210, 210, 210]); // bright grey
    const m = findGlow(img, 0.62, 0.08);
    expect(m[10 * 480 + 10]).toBe(1);
    expect(m[10 * 480 + 11]).toBe(0);
    expect(m[50 * 480 + 50]).toBe(0);
  });
});

describe('splitGlow', () => {
  it('routes candidates inside a light rect to that light, the rest to the general map', () => {
    const img = img480();
    put(img, 100, 140, [255, 200, 90]); // lamp bulb
    put(img, 400, 20, [60, 255, 240]); // a sign elsewhere
    const m = findGlow(img, 0.62, 0.08);
    const { general, perLight } = splitGlow(img, m, { desk_lamp: [90, 130, 20, 20], monitor: [300, 200, 10, 10] }, 0);
    expect(perLight.desk_lamp!.data[(140 * 480 + 100) * 4 + 3]).toBe(255);
    expect(perLight.desk_lamp!.data[(20 * 480 + 400) * 4 + 3]).toBe(0);
    expect(general!.data[(20 * 480 + 400) * 4 + 3]).toBe(255);
    expect(perLight.monitor).toBeUndefined(); // no candidates in its rect
  });

  it('shifts scene rects by the layer offset for wider layers', () => {
    const img = blank(500, 270);
    put(img, 110, 140, [255, 200, 90]); // scene x 100 + offset 10
    const m = findGlow(img, 0.62, 0.08);
    const { perLight, general } = splitGlow(img, m, { desk_lamp: [95, 135, 10, 10] }, 10);
    expect(perLight.desk_lamp).toBeDefined();
    expect(general).toBeNull();
  });
});

describe('splitGlow with an odd-width layer', () => {
  it('a fractional layer offset (485-wide layer → 2.5) still routes pixels to the light', () => {
    const img = blank(485, 270);
    put(img, 95, 146, [255, 200, 90]);
    const m = findGlow(img, 0.62, 0.08);
    const { perLight, general } = splitGlow(img, m, { desk_lamp: [73, 131, 40, 30] }, 2.5);
    expect(perLight.desk_lamp).toBeDefined();
    expect(general).toBeNull();
  });
});

describe('glowPreview', () => {
  it('outlines candidates in red', () => {
    const img = img480();
    put(img, 50, 50, [255, 60, 140]);
    const p = glowPreview(img, findGlow(img, 0.62, 0.08));
    expect([...p.data.slice((50 * 480 + 51) * 4, (50 * 480 + 51) * 4 + 3)]).toEqual([255, 0, 0]);
  });
});

describe('GlowLock (Review Focus 4)', () => {
  it('keys entries by name, compares installed files to the generated hash, and treats unrecorded existing files as hand-made', () => {
    const dir = tempDir('art-lock-');
    const f = path.join(dir, 'room_e.png');
    const lockFile = path.join(dir, 'glow.lock.json');
    const lock = new GlowLock(lockFile);
    expect(lock.isHandEdited('t/room_e.png', f)).toBe(false); // no file yet
    fs.writeFileSync(f, 'v1');
    expect(lock.isHandEdited('t/room_e.png', f)).toBe(true); // exists, never generated by us
    lock.record('t/room_e.png', Buffer.from('v1'));
    lock.save();
    const again = new GlowLock(lockFile);
    expect(again.isHandEdited('t/room_e.png', f)).toBe(false);
    fs.writeFileSync(f, 'edited by hand');
    expect(again.isHandEdited('t/room_e.png', f)).toBe(true);
    expect(Object.keys(JSON.parse(fs.readFileSync(lockFile, 'utf8')))).toEqual(['t/room_e.png']);
  });
});
